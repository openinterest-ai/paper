#!/usr/bin/env python3
"""Bake the OI site's live data: data.json (fleet + ticker + job list) and
one engine-room detail page per job the newsroom wallet has paid for.
Finds jobs automatically: lists recent network jobs, fetches detail for ids
it hasn't resolved, keeps the ones paid by the newsroom wallet, and caches
full detail in engine/jobs-full.json so nothing ages out of the API's
recent-jobs window. A detail page is only written if it is missing or was
generated by this script (marker comment), so curated pages are never
touched. Pure stdlib; safe to run from cron or CI."""
import html, json, os, re, time, urllib.request

WALLET = "0xbe80e5979313cf8aff2b8e54e615fe3ecd8358f5"
SEED_JOBS = [  # pre-wallet-era jobs, paid before the ops wallet convention
    "bea3fd5d-8fc8-4408-8d7b-f9748277763f",
    "414ba24a-5132-48dc-8cbd-db1f369016c2",
]
LABELS = {  # curated names; anything else gets an automatic label
    "bea3fd5d": "masthead sweep &middot; run 1 &middot; &#8470; 000 false start",
    "414ba24a": "masthead sweep &middot; run 2 &middot; 99 voices",
    "1ec72c86": "test edition 01",
    "ad7adaa3": "masthead adversarial audit &middot; 99 &rarr; 88",
    "bdc0925b": "test edition 02",
    "83bad12f": "test edition 03",
    "d2922feb": "test edition 04 &middot; full pipeline",
    "9ecefb0d": "test edition 05 &middot; full pipeline",
}
TERMINAL = {"completed", "failed", "cancelled"}
MARKER = "<!-- generated by bake.py; edits here are overwritten -->"

def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "openinterest-bake/3.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)

def auto_label(job):
    o = job.get("objective") or ""
    day = (job.get("createdAt") or "")[:10]
    if "TEST EDITION" in o:
        return f"test edition &middot; {day}"
    if o.lower().startswith("adversarially review"):
        return f"adversarial review &middot; {day}"
    tpl = (job.get("template") or "job").replace("skill:", "")
    return f"{tpl} &middot; {day}"

def detail_page(j):
    jid, short = j["id"], j["id"][:8]
    label = LABELS.get(short, auto_label(j))
    state = j.get("state", "?")
    tick = " &#10003;" if state == "completed" else ""
    created = (j.get("createdAt") or "")[:19].replace("T", " ") + " UTC"
    tpl = (j.get("template") or "").replace("skill:", "")
    objective = html.escape(j.get("objective") or "(objective not recorded)")
    objective = re.sub(r'(https?://[^\s\]"&]+)',
                       r'<a href="\1" target="_blank" rel="noreferrer" style="color:#c25663">\1</a>',
                       objective)
    receipts = ""
    for rv in j.get("reviews") or []:
        tx = rv.get("txHash")
        if tx:
            receipts += (f'<div style="margin-top:6px"><a href="https://etherscan.io/tx/{tx}" target="_blank" '
                         f'rel="noreferrer" style="color:#c25663;font-family:\'Geist Mono\',monospace;font-size:12px">'
                         f'receipt {tx[:10]}&hellip; on Ethereum mainnet &#8599;</a></div>')
    if not receipts:
        receipts = '<div style="color:#6f6d66;font-size:12px;margin-top:6px">receipt &middot; queued for the batcher</div>'
    return f"""<!doctype html>
{MARKER}
<html lang="en">
<head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Open Interest &mdash; job {short}</title>
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Anton&family=Inter:wght@400;500;600&family=Geist+Mono:wght@400;500&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../assets/oi.css">
</head>
<body class="dark">
<div style="border-bottom:1px solid #2a2a2c">
  <div class="wrap" style="max-width:1100px;padding:14px 20px;display:flex;flex-wrap:wrap;justify-content:space-between;align-items:baseline;gap:10px 20px">
    <a href="index.html" style="font-size:11px;letter-spacing:.08em;color:#a8a69e;text-decoration:none">&#8592; press hall</a>
    <span><span class="anton" style="font-size:18px;color:#e8e6dd">OPEN <span style="color:#c25663">I</span>NTEREST</span> <span style="font-size:10px;letter-spacing:.22em;color:#c25663;text-transform:uppercase;margin-left:10px">engine room</span></span>
  </div>
</div>
<main class="wrap" style="max-width:860px;padding:32px 20px 56px">
  <div style="font-size:10px;letter-spacing:.2em;color:#c25663;text-transform:uppercase;margin-bottom:8px">{label}</div>
  <h1 class="anton" style="margin:0 0 6px;font-size:clamp(26px,5vw,36px);line-height:1;color:#e8e6dd">JOB {short.upper()}</h1>
  <div style="font-size:11px;color:#a8a69e;margin-bottom:24px">{tpl} &middot; {state}{tick} &middot; opened {created} &middot; paid by <a href="https://explorer.imd.fun/wallet/{WALLET}" target="_blank" rel="noreferrer" style="color:#a8a69e">the newsroom wallet &#8599;</a></div>
  <div style="font-size:10px;letter-spacing:.2em;color:#a8a69e;text-transform:uppercase;margin-bottom:8px">the ask, verbatim</div>
  <div style="font-family:'Geist Mono',monospace;font-size:12px;line-height:1.7;white-space:pre-wrap;border:1px solid #2a2a2c;padding:20px;background:#141416;color:#c9c7bf;overflow-wrap:anywhere;margin-bottom:24px">{objective}</div>
  <div style="font-size:10px;letter-spacing:.2em;color:#a8a69e;text-transform:uppercase">onchain</div>
  {receipts}
  <div style="margin-top:24px;display:flex;flex-wrap:wrap;gap:16px;font-size:12px">
    <a href="https://explorer.imd.fun/jobs/{jid}" target="_blank" rel="noreferrer" style="color:#e8e6dd">the answers, on the network explorer &#8599;</a>
  </div>
</main>
<footer style="border-top:1px solid #2a2a2c;padding:18px 16px">
  <div class="wrap" style="max-width:1100px;display:flex;flex-wrap:wrap;justify-content:space-between;gap:10px 24px;font-size:10px;letter-spacing:.14em;text-transform:uppercase;color:#a8a69e">
    <span>nothing here is written for you; it is simply not hidden</span>
    <span><a href="https://explorer.imd.fun/wallet/{WALLET}" target="_blank" rel="noreferrer" style="color:#a8a69e">newsroom wallet &#8599;</a></span>
  </div>
</footer>
</body>
</html>
"""

# ---- gather -----------------------------------------------------------------
full = {}
try:
    full = {j["id"]: j for j in json.load(open("engine/jobs-full.json")).get("jobs", [])}
except Exception:
    pass

fleet = {}
try:
    c = get("https://api.imd.fun/contributors")
    fleet = {"enrolled": len(c.get("contributors", [])), "receipts": c.get("receipts", 0)}
except Exception as e:
    print("contributors:", e)

candidates = list(SEED_JOBS)
try:
    recent = get("https://api.imd.fun/jobs")
    candidates += [j["id"] for j in recent.get("jobs", [])]
except Exception as e:
    print("jobs list:", e)

for jid in candidates:
    prior = full.get(jid)
    if prior and prior.get("state") in TERMINAL and prior.get("_ours") is not None:
        continue
    try:
        j = get(f"https://api.imd.fun/jobs/{jid}")
    except Exception as e:
        print(jid, e)
        continue
    j["_ours"] = jid in SEED_JOBS or (j.get("paidBy") or "").lower() == WALLET
    full[jid] = j

ours = sorted((j for j in full.values() if j.get("_ours")), key=lambda j: j.get("createdAt") or "")

# ---- write ------------------------------------------------------------------
json.dump({"jobs": list(full.values())}, open("engine/jobs-full.json", "w"))

pages = 0
for j in ours:
    path = f"engine/job-{j['id'][:8]}.html"
    if os.path.exists(path) and MARKER not in open(path).read(2048):
        continue  # curated page; never touch
    open(path, "w").write(detail_page(j))
    pages += 1

events, joblist = [], []
for j in ours:
    short = j["id"][:8]
    state = j.get("state", "?")
    tpl = (j.get("template") or "").replace("skill:", "")
    tick = " ✓" if state == "completed" else ""
    events.append(f"job {short} &middot; {tpl} &middot; {state}{tick}")
    joblist.append({
        "id": j["id"], "short": short, "state": state, "template": tpl,
        "createdAt": j.get("createdAt", ""),
        "label": LABELS.get(short, auto_label(j)),
        "page": f"job-{short}.html",
    })
events += [
    "edition &#8470; 000 &middot; the masthead &middot; false start kept on purpose",
    "masthead audited &middot; 99 &rarr; 88 &middot; the record is public",
    "payroll &rarr; the panel &middot; per protocol",
    "no human edits &middot; every decision on-chain",
]

json.dump({
    "updated": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    "fleet": {"online": None, **fleet},
    "jobs": joblist,
    "events": events,
}, open("data.json", "w"))
print("baked", len(ours), "jobs,", pages, "pages written,", len(events), "events")
